## ---- test-rProject-ai-global
lapply(
  X = 1,
  FUN = function(i,
                 text) {
    root <- tempfile(pattern = "aiglobal")
    home <- tempfile(pattern = "home")
    source_dir <- file.path(root, ".setup", "ai", "global")
    dir.create(
      path = source_dir,
      recursive = TRUE
    )
    dir.create(
      path = file.path(home, ".claude"),
      recursive = TRUE
    )
    writeLines(
      text = c("# Global", "", "- plan first"),
      con = file.path(source_dir, "AGENTS.md")
    )
    writeLines(
      text = "{\"theme\": \"dark\", \"permissions\": {}}",
      con = file.path(source_dir, "claude-settings.json")
    )
    writeLines(
      text = "{\"theme\": \"light\"}",
      con = file.path(home, ".claude", "settings.json")
    )
    targets <- file.path(
      home,
      c(
        ".claude/CLAUDE.md",
        ".codex/AGENTS.md",
        ".copilot/copilot-instructions.md",
        ".claude/settings.json"
      )
    )
    first <- suppressMessages(
      expr = AIGlobal(
        path = root,
        home = home
      )
    )
    testthat::test_that(
      paste(text, "installs all files"),
      {
        testthat::expect_equal(
          object = sort(x = first),
          expected = sort(x = targets)
        )
        testthat::expect_true(
          object = all(file.exists(targets))
        )
      }
    )
    testthat::test_that(
      paste(text, "adds the header"),
      {
        claude <- readLines(con = file.path(home, ".claude", "CLAUDE.md"))
        testthat::expect_true(
          object = grepl(
            pattern = "Generated by rProject::AIGlobal",
            x = claude[1]
          )
        )
        testthat::expect_equal(
          object = claude[-(1:2)],
          expected = c("# Global", "", "- plan first")
        )
      }
    )
    testthat::test_that(
      paste(text, "sets mode 600"),
      {
        testthat::skip_on_os(os = "windows")
        testthat::expect_true(
          object = all(
            format(x = file.info(targets)$mode) == "600"
          )
        )
      }
    )
    testthat::test_that(
      paste(text, "backs up a different file"),
      {
        testthat::expect_equal(
          object = readLines(
            con = file.path(home, ".claude", "settings.json.bak")
          ),
          expected = "{\"theme\": \"light\"}"
        )
      }
    )
    second <- suppressMessages(
      expr = AIGlobal(
        path = root,
        home = home
      )
    )
    testthat::test_that(
      paste(text, "writes nothing when up to date"),
      {
        testthat::expect_null(object = second)
      }
    )
    testthat::test_that(
      paste(text, "stops without AGENTS.md"),
      {
        testthat::expect_error(
          object = AIGlobal(
            path = tempfile(),
            home = home
          )
        )
      }
    )
    unlink(
      x = c(root, home),
      recursive = TRUE
    )
    # in the source tree: the vignette's keywords match the global
    # instructions (.setup/ai/global/AGENTS.md is private)
    project <- file.path("..", "..")
    global <- file.path(project, ".setup", "ai", "global", "AGENTS.md")
    vignette <- file.path(project, "vignettes", "structure.Rmd")
    if (file.exists(global) && file.exists(vignette)) {
      testthat::test_that(
        paste(text, "the vignette's keywords match the instructions"),
        {
          keywords <- function(lines, pattern) {
            sub(
              pattern = pattern,
              replacement = "\\1",
              x = grep(pattern = pattern, x = lines, value = TRUE)
            )
          }
          defined <- keywords(
            lines = readLines(con = global, warn = FALSE),
            pattern = "^- \"([^\"]+)\".*"
          )
          listed <- keywords(
            lines = readLines(con = vignette, warn = FALSE),
            pattern = "^\\| \"([^\"]+)\" \\|.*"
          )
          testthat::expect_setequal(
            object = listed,
            expected = c(defined, "handoff")
          )
        }
      )
    }
  },
  text = "test-rProject-ai-global"
)
