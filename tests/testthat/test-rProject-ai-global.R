## ---- test-rProject-ai-global
lapply(
  X = 1,
  FUN = function(i,
                 text) {
    root <- tempfile(pattern = "aiglobal")
    home <- tempfile(pattern = "home")
    source_dir <- file.path(root, ".setup", "ai", "global")
    dir.create(
      source_dir,
      recursive = TRUE
    )
    dir.create(
      file.path(home, ".claude"),
      recursive = TRUE
    )
    writeLines(
      text = c("# Global", "", "- plan first"),
      con = file.path(source_dir, "AGENTS.md")
    )
    writeLines(
      text = "{\"theme\": \"dark\", \"permissions\": {}}",
      con = file.path(source_dir, "claude-settings.json")
    )
    writeLines(
      text = "{\"theme\": \"light\"}",
      con = file.path(home, ".claude", "settings.json")
    )
    targets <- file.path(
      home,
      c(
        ".claude/CLAUDE.md",
        ".codex/AGENTS.md",
        ".copilot/copilot-instructions.md",
        ".claude/settings.json"
      )
    )
    first <- suppressMessages(
      AIGlobal(
        path = root,
        home = home
      )
    )
    testthat::test_that(
      paste(text, "installs all files"),
      {
        testthat::expect_equal(
          sort(first),
          sort(targets)
        )
        testthat::expect_true(
          all(file.exists(targets))
        )
      }
    )
    testthat::test_that(
      paste(text, "adds the header"),
      {
        claude <- readLines(file.path(home, ".claude", "CLAUDE.md"))
        testthat::expect_true(
          grepl(
            pattern = "Generated by rProject::AIGlobal",
            x = claude[1]
          )
        )
        testthat::expect_equal(
          claude[-(1:2)],
          c("# Global", "", "- plan first")
        )
      }
    )
    testthat::test_that(
      paste(text, "sets mode 600"),
      {
        testthat::skip_on_os("windows")
        testthat::expect_true(
          all(
            format(file.info(targets)$mode) == "600"
          )
        )
      }
    )
    testthat::test_that(
      paste(text, "backs up a different file"),
      {
        testthat::expect_equal(
          readLines(file.path(home, ".claude", "settings.json.bak")),
          "{\"theme\": \"light\"}"
        )
      }
    )
    second <- suppressMessages(
      AIGlobal(
        path = root,
        home = home
      )
    )
    testthat::test_that(
      paste(text, "writes nothing when up to date"),
      {
        testthat::expect_null(second)
      }
    )
    testthat::test_that(
      paste(text, "stops without AGENTS.md"),
      {
        testthat::expect_error(
          AIGlobal(
            path = tempfile(),
            home = home
          )
        )
      }
    )
    unlink(
      c(root, home),
      recursive = TRUE
    )
  },
  text = "test-rProject-ai-global"
)
