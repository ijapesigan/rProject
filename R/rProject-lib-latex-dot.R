.LibLatex <- function(x,
                      escape = TRUE) {
  # non-ASCII characters as LaTeX; with escape = TRUE, also % and &
  # (for text fields, not for doi or url)
  # pairs of (character, LaTeX); a matrix, not names, so that R versions
  # without a UTF-8 locale need not translate the characters into symbols
  map <- matrix(
    data = c(
      "\u00e1", "{\\'a}", "\u00e0", "{\\`a}", "\u00e2", "{\\^a}",
      "\u00e4", "{\\\"a}", "\u00e3", "{\\~a}", "\u00e5", "{\\r a}",
      "\u0101", "{\\=a}", "\u0103", "{\\u a}", "\u0105", "{\\k a}",
      "\u00c1", "{\\'A}", "\u00c0", "{\\`A}", "\u00c2", "{\\^A}",
      "\u00c4", "{\\\"A}", "\u00c3", "{\\~A}", "\u00c5", "{\\r A}",
      "\u00e7", "{\\c c}", "\u0107", "{\\'c}", "\u010d", "{\\v c}",
      "\u00c7", "{\\c C}", "\u0106", "{\\'C}", "\u010c", "{\\v C}",
      "\u010f", "{\\v d}", "\u0111", "{\\dj}", "\u010e", "{\\v D}",
      "\u00e9", "{\\'e}", "\u00e8", "{\\`e}", "\u00ea", "{\\^e}",
      "\u00eb", "{\\\"e}", "\u011b", "{\\v e}", "\u0119", "{\\k e}",
      "\u0113", "{\\=e}", "\u00c9", "{\\'E}", "\u00c8", "{\\`E}",
      "\u00ca", "{\\^E}", "\u00cb", "{\\\"E}", "\u011a", "{\\v E}",
      "\u011f", "{\\u g}", "\u011e", "{\\u G}",
      "\u00ed", "{\\'i}", "\u00ec", "{\\`i}", "\u00ee", "{\\^i}",
      "\u00ef", "{\\\"i}", "\u0131", "{\\i}", "\u00cd", "{\\'I}",
      "\u00ce", "{\\^I}", "\u0130", "{\\.I}",
      "\u0142", "{\\l}", "\u0141", "{\\L}", "\u013e", "{\\v l}",
      "\u00f1", "{\\~n}", "\u0144", "{\\'n}", "\u0148", "{\\v n}",
      "\u00d1", "{\\~N}",
      "\u00f3", "{\\'o}", "\u00f2", "{\\`o}", "\u00f4", "{\\^o}",
      "\u00f6", "{\\\"o}", "\u00f5", "{\\~o}", "\u0151", "{\\H o}",
      "\u00f8", "{\\o}", "\u00d3", "{\\'O}", "\u00d2", "{\\`O}",
      "\u00d4", "{\\^O}", "\u00d6", "{\\\"O}", "\u00d8", "{\\O}",
      "\u0150", "{\\H O}",
      "\u0159", "{\\v r}", "\u0158", "{\\v R}",
      "\u015b", "{\\'s}", "\u0161", "{\\v s}", "\u015f", "{\\c s}",
      "\u015a", "{\\'S}", "\u0160", "{\\v S}", "\u015e", "{\\c S}",
      "\u00df", "{\\ss}", "\u0165", "{\\v t}", "\u0163", "{\\c t}",
      "\u00fa", "{\\'u}", "\u00f9", "{\\`u}", "\u00fb", "{\\^u}",
      "\u00fc", "{\\\"u}", "\u016f", "{\\r u}", "\u0171", "{\\H u}",
      "\u016b", "{\\=u}", "\u00da", "{\\'U}", "\u00dc", "{\\\"U}",
      "\u00fd", "{\\'y}", "\u00ff", "{\\\"y}", "\u00dd", "{\\'Y}",
      "\u017a", "{\\'z}", "\u017c", "{\\.z}", "\u017e", "{\\v z}",
      "\u0179", "{\\'Z}", "\u017b", "{\\.Z}", "\u017d", "{\\v Z}",
      "\u00e6", "{\\ae}", "\u00c6", "{\\AE}", "\u0153", "{\\oe}",
      "\u0152", "{\\OE}",
      "\u2010", "-", "\u2011", "-", "\u2012", "--", "\u2013", "--",
      "\u2014", "---", "\u2212", "--",
      "\u2018", "`", "\u2019", "'", "\u201c", "``", "\u201d", "''",
      "\u2026", "\\ldots{}", "\u00a0", " ", "\u2009", " ", "\u202f", " ",
      "\u00d7", "$\\times$", "\u00b1", "$\\pm$", "\u2264", "$\\leq$",
      "\u2265", "$\\geq$", "\u2248", "$\\approx$", "\u2260", "$\\neq$",
      "\u00b2", "$^2$", "\u00b3", "$^3$", "\u00b0", "$^\\circ$",
      "\u03b1", "$\\alpha$", "\u03b2", "$\\beta$", "\u03b3", "$\\gamma$",
      "\u03b4", "$\\delta$", "\u03b5", "$\\epsilon$", "\u03b8", "$\\theta$",
      "\u03bb", "$\\lambda$", "\u03bc", "$\\mu$", "\u03c0", "$\\pi$",
      "\u03c1", "$\\rho$", "\u03c3", "$\\sigma$", "\u03c4", "$\\tau$",
      "\u03c6", "$\\phi$", "\u03c7", "$\\chi$", "\u03c8", "$\\psi$",
      "\u03c9", "$\\omega$", "\u0394", "$\\Delta$", "\u03a3", "$\\Sigma$"
    ),
    ncol = 2,
    byrow = TRUE
  )
  x <- enc2utf8(x)
  if (escape) {
    # an unescaped % starts a LaTeX comment; & is an alignment tab
    x <- gsub(pattern = "(^|[^\\\\])([%&])", replacement = "\\1\\\\\\2", x = x)
    x <- gsub(pattern = "(^|[^\\\\])([%&])", replacement = "\\1\\\\\\2", x = x)
  }
  for (i in seq_len(nrow(map))) {
    x <- gsub(pattern = map[i, 1], replacement = map[i, 2], x = x, fixed = TRUE)
  }
  x
}
