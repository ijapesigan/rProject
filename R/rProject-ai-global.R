#' Install Global AI Instructions
#'
#' Copies the global AI instructions and Claude settings
#' from `.setup/ai/global` in the project
#' to the configuration folders of Claude Code, Codex, and GitHub Copilot
#' in the home directory.
#' Files are written only when their content changed.
#' Existing files that differ are backed up with the suffix `.bak`.
#'
#' | Source | Installed to |
#' |---|---|
#' | `AGENTS.md` | `~/.claude/CLAUDE.md` |
#' | `AGENTS.md` | `~/.codex/AGENTS.md` |
#' | `AGENTS.md` | `~/.copilot/copilot-instructions.md` |
#' | `claude-settings.json` | `~/.claude/settings.json` |
#'
#' `claude-settings.json` is merged into an existing `settings.json`:
#' its keys win, permission rules are added to the existing ones,
#' and other keys are kept.
#'
#' @author Ivan Jacob Agaloos Pesigan
#'
#' @inheritParams LibPaths
#' @param home Character string.
#'   Home directory.
#' @return Returns the paths of the files that were written.
#' @export
AIGlobal <- function(path,
                     home = Sys.getenv("HOME")) {
  source_dir <- file.path(
    path,
    ".setup",
    "ai",
    "global"
  )
  agents <- file.path(
    source_dir,
    "AGENTS.md"
  )
  settings <- file.path(
    source_dir,
    "claude-settings.json"
  )
  if (!file.exists(agents)) {
    stop(
      paste0(
        "\n\n",
        agents,
        " does not exist.\n\n"
      ),
      call. = FALSE
    )
  }
  instructions <- c(
    paste0(
      "<!-- Generated by rProject::AIGlobal() ",
      "from .setup/ai/global/AGENTS.md. Edit the source. -->"
    ),
    "",
    readLines(
      con = agents,
      warn = FALSE
    )
  )
  targets <- list(
    list(
      file = file.path(home, ".claude", "CLAUDE.md"),
      text = instructions
    ),
    list(
      file = file.path(home, ".codex", "AGENTS.md"),
      text = instructions
    ),
    list(
      file = file.path(home, ".copilot", "copilot-instructions.md"),
      text = instructions
    )
  )
  if (file.exists(settings)) {
    settings_file <- file.path(home, ".claude", "settings.json")
    settings_text <- readLines(
      con = settings,
      warn = FALSE
    )
    # merge into the installed settings: keys and permission rules
    # added on this machine (e.g., an MCP allow) are kept
    if (file.exists(settings_file)) {
      installed <- tryCatch(
        expr = jsonlite::fromJSON(
          txt = settings_file,
          simplifyVector = FALSE
        ),
        error = function(e) {
          NULL
        }
      )
      if (!is.null(installed)) {
        settings_text <- strsplit(
          x = as.character(
            jsonlite::toJSON(
              x = .AIGlobalMerge(
                existing = installed,
                source = jsonlite::fromJSON(
                  txt = settings,
                  simplifyVector = FALSE
                )
              ),
              auto_unbox = TRUE,
              pretty = TRUE,
              null = "null"
            )
          ),
          split = "\n",
          fixed = TRUE
        )[[1]]
      }
    }
    targets <- c(
      targets,
      list(
        list(
          file = settings_file,
          text = settings_text
        )
      )
    )
  }
  written <- unlist(
    lapply(
      X = targets,
      FUN = function(target) {
        .AIGlobalWrite(
          file = target$file,
          text = target$text
        )
      }
    )
  )
  if (length(written) > 0L) {
    message(
      paste0(
        "\n\nWritten:\n",
        paste0(
          written,
          collapse = "\n"
        ),
        "\n\n"
      )
    )
  } else {
    message("\n\nGlobal AI instructions are up to date.\n\n")
  }
  invisible(written)
}
