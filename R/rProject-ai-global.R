#' Install Global AI Instructions
#'
#' Copies the global AI instructions and Claude settings
#' from `.setup/ai/global` in the project
#' to the configuration folders of Claude Code, Codex, and GitHub Copilot
#' in the home directory.
#' Files are written only when their content changed.
#' Existing files that differ are backed up with the suffix `.bak`.
#'
#' | Source | Installed to |
#' |---|---|
#' | `AGENTS.md` | `~/.claude/CLAUDE.md` |
#' | `AGENTS.md` | `~/.codex/AGENTS.md` |
#' | `AGENTS.md` | `~/.copilot/instructions/AGENTS.md` |
#' | `claude-settings.json` | `~/.claude/settings.json` |
#'
#' GitHub Copilot reads `~/.copilot/instructions`
#' only when the environment variable `COPILOT_CUSTOM_INSTRUCTIONS_DIRS`
#' includes that folder.
#'
#' @author Ivan Jacob Agaloos Pesigan
#'
#' @inheritParams LibPaths
#' @param home Character string.
#'   Home directory.
#' @return Returns the paths of the files that were written.
#' @export
AIGlobal <- function(path,
                     home = Sys.getenv("HOME")) {
  source_dir <- file.path(
    path,
    ".setup",
    "ai",
    "global"
  )
  agents <- file.path(
    source_dir,
    "AGENTS.md"
  )
  settings <- file.path(
    source_dir,
    "claude-settings.json"
  )
  if (!file.exists(agents)) {
    stop(
      paste0(
        "\n\n",
        agents,
        " does not exist.\n\n"
      ),
      call. = FALSE
    )
  }
  instructions <- c(
    paste0(
      "<!-- Generated by rProject::AIGlobal() ",
      "from .setup/ai/global/AGENTS.md. Edit the source. -->"
    ),
    "",
    readLines(
      con = agents,
      warn = FALSE
    )
  )
  targets <- list(
    list(
      file = file.path(home, ".claude", "CLAUDE.md"),
      text = instructions
    ),
    list(
      file = file.path(home, ".codex", "AGENTS.md"),
      text = instructions
    ),
    list(
      file = file.path(home, ".copilot", "instructions", "AGENTS.md"),
      text = instructions
    )
  )
  if (file.exists(settings)) {
    targets <- c(
      targets,
      list(
        list(
          file = file.path(home, ".claude", "settings.json"),
          text = readLines(
            con = settings,
            warn = FALSE
          )
        )
      )
    )
  }
  written <- unlist(
    lapply(
      X = targets,
      FUN = function(target) {
        .AIGlobalWrite(
          file = target$file,
          text = target$text
        )
      }
    )
  )
  if (length(written) > 0L) {
    message(
      paste0(
        "\n\nWritten:\n",
        paste0(
          written,
          collapse = "\n"
        ),
        "\n\n"
      )
    )
  } else {
    message("\n\nGlobal AI instructions are up to date.\n\n")
  }
  invisible(written)
}
