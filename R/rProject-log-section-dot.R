.LogSection <- function(path,
                        private,
                        log) {
  logs <- c(
    file.path(".setup", "logs", log),
    file.path(".setup", "logs", "index.md")
  )
  delete <- character(length = 0)
  linked <- character(length = 0)
  if (is.null(x = private)) {
    new <- "TODO"
    edited <- "TODO"
  } else {
    status <- .VerifyChanges(
      path = path,
      private = private
    )
    new <- names(x = status)[status == "missing in the private repository"]
    edited <- names(x = status)[status == "different"]
    # in the private repository but not here
    delete <- names(x = status)[status == "missing locally"]
    # this log and the index always go up with the change set
    in_private <- file.exists(file.path(private, logs))
    new <- union(x = new, y = logs[!in_private])
    edited <- union(x = edited, y = logs[in_private])
    # links to the functions repository are refreshed, never uploaded
    is_linked <- grepl(
      pattern = "^\\.setup/r-dependencies/",
      x = names(x = status)
    )
    linked <- names(x = status)[is_linked]
    new <- setdiff(x = new, y = linked)
    edited <- setdiff(x = edited, y = linked)
    delete <- setdiff(x = delete, y = linked)
    # .setup/todo/ is the user's, edited on Overleaf at any time;
    # .setup/repo/ can be missing here without being deleted
    todo <- grepl(pattern = "^\\.setup/todo/", x = names(x = status))
    keep <- grepl(pattern = "^\\.setup/(todo|repo)/", x = names(x = status))
    new <- setdiff(x = new, y = names(x = status)[todo])
    edited <- setdiff(x = edited, y = names(x = status)[todo])
    delete <- setdiff(x = delete, y = names(x = status)[keep])
  }
  bullets <- function(x) {
    ifelse(
      test = length(x = x) > 0L,
      yes = list(paste("-", x)),
      no = list("- (none)")
    )[[1]]
  }
  c(
    "## Files to update in Overleaf",
    "",
    "### New",
    bullets(new),
    "",
    "### Edited",
    bullets(edited),
    "",
    "### Generated by make (do not upload)",
    "- NAMESPACE, man/, and other files that make regenerates",
    paste(
      "- AGENTS.md, CLAUDE.md, .github/copilot-instructions.md:",
      "AI() writes them at make project; private and local"
    ),
    "",
    "### Delete in Overleaf",
    if (length(x = delete) > 0L) {
      paste(
        "In the private repository but not here. Delete each one, unless it",
        "was added in Overleaf (then copy it here instead)."
      )
    },
    bullets(delete),
    "",
    if (length(x = linked) > 0L) {
      c(
        paste(
          "### Linked from functions",
          "(refresh the link in Overleaf; do not upload)"
        ),
        "If one differs from functions, update functions first.",
        paste("-", linked),
        ""
      )
    }
  )
}
