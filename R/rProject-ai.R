#' Write the Project's AI Instructions
#'
#' Writes the instruction files that AI tools read in this project,
#' on top of the global instructions installed by [AIGlobal()].
#'
#' - `.setup/ai/project.md`: project facts that the user maintains.
#'   Created once and never overwritten.
#' - `AGENTS.md` (Codex, Copilot CLI, Claude through `CLAUDE.md`),
#'   `CLAUDE.md` (Claude Code), and `.github/copilot-instructions.md`
#'   (Copilot in the IDE): generated, and rewritten when they change.
#'
#' All of them are private (gitignored and excluded from the package build).
#'
#' The project type and the image come from `type` and `sif`,
#' else from an `ai` list in `.setup/scripts/project.R`
#' (e.g., `ai <- list(type = c("manuscript", "simulation"), sif = "x.sif")`),
#' else they are detected:
#' `"simulation"` if `.sim` exists,
#' `"manuscript"` if a `*-manuscript*.Rtex` exists
#' or the name starts with `man`,
#' `"library"` for `lib-*`, `"talk"` for `talks*`,
#' otherwise `"package"`; the image defaults to `docs.sif`.
#'
#' @author Ivan Jacob Agaloos Pesigan
#'
#' @inheritParams LibPaths
#' @param type Character vector.
#'   Project types: any of `"package"`, `"manuscript"`, `"simulation"`,
#'   `"library"`, and `"talk"`.
#' @param sif Character string.
#'   File name of the Apptainer image.
#' @return Returns the paths of the files that were written, invisibly.
#' @export
AI <- function(path,
               type = NULL,
               sif = NULL) {
  project <- .VerifyProject(path = path)
  settings <- .AISettings(path = path)
  if (is.null(type)) {
    type <- settings$type
  }
  if (is.null(type)) {
    type <- .AIType(path = path, project = project)
  }
  if (is.null(sif)) {
    sif <- settings$sif
  }
  if (is.null(sif)) {
    sif <- "docs.sif"
  }
  values <- c(
    project = project,
    types = paste(type, collapse = ", "),
    sif = sif,
    folders = .AIRows(
      type = type,
      rows = list(
        manuscript = paste(
          "| `.setup/latex/` |",
          "manuscript sources (`.Rtex`) and figures |"
        ),
        simulation = c(
          "| `.sim/` | simulation scripts (SLURM, GNU Parallel) |",
          "| `.sif/` | the image (local only; never uploaded) |"
        )
      )
    ),
    targets = .AIRows(
      type = type,
      rows = list(
        manuscript = c(
          "| `make latex` | knit and compile the manuscript |",
          "| `make pdf` | a clean LaTeX build |"
        )
      )
    ),
    sections = paste(
      vapply(
        X = intersect(
          c("manuscript", "simulation", "package", "library", "talk"),
          type
        ),
        FUN = function(x) {
          paste(
            .AITemplate(file = paste0("section-", x, ".md")),
            collapse = "\n"
          )
        },
        FUN.VALUE = character(1)
      ),
      collapse = "\n"
    )
  )
  header <- paste0(
    "<!-- Generated by rProject::AI(). Do not edit; ",
    "edit .setup/ai/project.md, or the ai list in .setup/scripts/project.R. -->"
  )
  agents <- c(
    header,
    "",
    .AIFill(text = .AITemplate(file = "agents.md"), values = values)
  )
  written <- c(
    .AIWrite(
      file = file.path(path, "AGENTS.md"),
      text = agents
    ),
    .AIWrite(
      file = file.path(path, "CLAUDE.md"),
      text = c(header, "", "@AGENTS.md", "@.setup/ai/project.md")
    ),
    .AIWrite(
      file = file.path(path, ".github", "copilot-instructions.md"),
      text = c(
        header,
        "",
        .AIFill(
          text = .AITemplate(file = "copilot-instructions.md"),
          values = values
        )
      )
    )
  )
  project_md <- file.path(path, ".setup", "ai", "project.md")
  if (!file.exists(project_md)) {
    written <- c(
      written,
      .AIWrite(
        file = project_md,
        text = .AIFill(text = .AITemplate(file = "project.md"), values = values)
      )
    )
  }
  message(
    paste0(
      "\n\nAI instructions for ",
      project,
      " (",
      values[["types"]],
      "; ",
      sif,
      "): ",
      ifelse(
        length(written) > 0L,
        paste0("wrote ", paste(basename(written), collapse = ", ")),
        "up to date"
      ),
      ".\n\n"
    )
  )
  invisible(written)
}
